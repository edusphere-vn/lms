import { initializeTestEnvironment, assertSucceeds, assertFails } from "@firebase/rules-unit-testing";
import { readFileSync } from "fs";
import { doc, getDoc, setDoc, updateDoc } from "firebase/firestore";
const env = await initializeTestEnvironment({ projectId: "esvn-lms", firestore: { rules: readFileSync("firestore.rules","utf8"), host:"127.0.0.1", port:8080 }});
await env.withSecurityRulesDisabled(async (c) => {
  const d = c.firestore();
  await setDoc(doc(d,"students/ES112"), { teacherIds:["T1"], agencyId:"OEC" });
  await setDoc(doc(d,"sessions/s1"), { teacherId:"T1", scs:["ES112"], agencyIds:["OEC"], attendance:{ES112:"Present"}, feedback:"x" });
  await setDoc(doc(d,"sessions/s2"), { teacherId:"T1", scs:["ES112"], agencyIds:["OEC"], locked:true });
  await setDoc(doc(d,"sessions/s3"), { teacherId:"T2", scs:["ES999"], agencyIds:["X"] });
  await setDoc(doc(d,"users/u1"), { role:"teacher", mustChangePassword:true });
  await setDoc(doc(d,"billing/b1"), { invoice: 100 });
  await setDoc(doc(d,"public_reports/abc"), { sc:"ES112" });
  await setDoc(doc(d,"evaluations/e1"), { sc:"ES112", teacherId:"T1", agencyId:"OEC", status:"Draft" });
});
const as = (uid, claims) => env.authenticatedContext(uid, claims).firestore();
const t = as("u1",{role:"teacher",teacherId:"T1"}), t2 = as("u2",{role:"teacher",teacherId:"T2"});
const s = as("u3",{role:"student",sc:"ES112"}), s2 = as("u4",{role:"student",sc:"ES999"});
const a = as("u5",{role:"admin"}), ag = as("u6",{role:"agency",agencyId:"OEC"});
const anon = env.unauthenticatedContext().firestore();
let pass=0, fail=0;
const T = async (name, p) => { try { await p; pass++; } catch(e){ fail++; console.log("FAIL:", name); } };
await T("teacher reads own session", assertSucceeds(getDoc(doc(t,"sessions/s1"))));
await T("teacher cannot read others' session", assertFails(getDoc(doc(t,"sessions/s3"))));
await T("teacher writes report fields", assertSucceeds(updateDoc(doc(t,"sessions/s1"), { feedback:"ok" })));
await T("teacher cannot change date/teacher", assertFails(updateDoc(doc(t,"sessions/s1"), { teacherId:"T2" })));
await T("teacher cannot edit locked session", assertFails(updateDoc(doc(t,"sessions/s2"), { feedback:"late" })));
await T("admin cannot edit locked session", assertFails(updateDoc(doc(a,"sessions/s2"), { feedback:"late" })));
await T("admin edits normal session", assertSucceeds(updateDoc(doc(a,"sessions/s1"), { topic:"t" })));
await T("student reads own session", assertSucceeds(getDoc(doc(s,"sessions/s1"))));
await T("other student blocked", assertFails(getDoc(doc(s2,"sessions/s1"))));
await T("agency reads its session", assertSucceeds(getDoc(doc(ag,"sessions/s1"))));
await T("teacher reads own student", assertSucceeds(getDoc(doc(t,"students/ES112"))));
await T("other teacher blocked from student", assertFails(getDoc(doc(t2,"students/ES112"))));
await T("teacher cannot read billing", assertFails(getDoc(doc(t,"billing/b1"))));
await T("admin reads billing", assertSucceeds(getDoc(doc(a,"billing/b1"))));
await T("public report get by token", assertSucceeds(getDoc(doc(anon,"public_reports/abc"))));
await T("student cannot self-promote user doc", assertFails(updateDoc(doc(as("u1",{role:"teacher"}),"users/u1"), { role:"admin" })));
await T("user clears mustChangePassword", assertSucceeds(updateDoc(doc(as("u1",{role:"teacher"}),"users/u1"), { mustChangePassword:false })));
await T("user cannot set mustChangePassword true", assertFails(updateDoc(doc(as("u1",{role:"teacher"}),"users/u1"), { mustChangePassword:true })));
await T("student cannot see draft evaluation", assertFails(getDoc(doc(s,"evaluations/e1"))));
await T("teacher cannot approve own evaluation", assertFails(updateDoc(doc(t,"evaluations/e1"), { status:"Approved" })));
await T("anon blocked from sessions", assertFails(getDoc(doc(anon,"sessions/s1"))));
console.log("pass",pass,"fail",fail);
await env.cleanup();
